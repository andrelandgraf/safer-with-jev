function AskStory({
  title,
  blurb,
  examples,
  heds,
  defaultExample,
  curl,
  idPrefix,
  openHref,
  openLabel,
  rows = 4,
}: {
  title: string;
  blurb: string;
  examples: AskExample[];
  heds: AskExample[];
  defaultExample: AskExample;
  curl: string;
  idPrefix: string;
  openHref: string;
  openLabel: string;
  rows?: number;
}) {
  const inspect = useInspectCall();
  const [q, setQ] = useState(defaultExample.q);
  const [t, setT] = useState(defaultExample.t);
  const [error, setError] = useState<string | null>(null);
  const pending = inspect.state.kind === "pending";
  const chips = examples.filter((example) => !heds.some((hed) => hed.id === example.id));
  const questionId = `${idPrefix}-q`;
  const textId = `${idPrefix}-t`;

  function load(example: AskExample) {
    setError(null);
    setQ(example.q);
    setT(example.t);
    void inspect.run({ kind: "ask", q: example.q, t: example.t });
  }

  function submit(event: FormEvent) {
    event.preventDefault();
    if (q.trim() === "" || t.trim() === "") {
      setError("Question and text are required.");
      return;
    }
    if (tooLarge(q) || tooLarge(t)) {
      setError("Question and text must each be 256 KiB or smaller.");
      return;
    }
    setError(null);
    void inspect.run({ kind: "ask", q, t });
  }

  return (
    <article className="story" aria-busy={pending}>
      <h3>{title}</h3>
      <p>{blurb}</p>
      {heds.length > 0 ? (
        <ul>
          {heds.map((example) => (
            <li key={example.id}>
              <button type="button" className="hed" disabled={pending} onClick={() => load(example)}>
                {example.label}
              </button>
            </li>
          ))}
        </ul>
      ) : null}
      <p className="demo-more">
        {chips.map((example) => (
          <button
            key={example.id}
            type="button"
            className="chip"
            disabled={pending}
            onClick={() => load(example)}
          >
            {example.label}
          </button>
        ))}
        <a className="demo-open" href={openHref}>
          {openLabel}
        </a>
      </p>
      <form onSubmit={submit}>
        <label htmlFor={questionId}>Question</label>
        <input
          id={questionId}
          name="q"
          value={q}
          disabled={pending}
          onChange={(event) => {
            inspect.invalidate();
            setError(null);
            setQ(event.target.value);
          }}
        />
        <label htmlFor={textId}>Text</label>
        <textarea
          id={textId}
          name="t"
          rows={rows}
          value={t}
          disabled={pending}
          onChange={(event) => {
            inspect.invalidate();
            setError(null);
            setT(event.target.value);
          }}
        />
        {error ? <p role="alert">{error}</p> : null}
        <button type="submit" disabled={pending}>
          {pending ? "On the wire" : "Ask Jev"}
        </button>
      </form>
      <JudgmentResult state={inspect.state} scroll={false} />
      <details>
        <summary>curl</summary>
        <pre>
          <code>{curl}</code>
        </pre>
      </details>
    </article>
  );
}

